"""Scope-fix proof: the config hashes, and what the gate admits post-fix.

Resolves the numbers the 2026-10-15 postseason scope fix asserts in its PR
body, in `docs/mvp-design.md` and in the `hash_lineage` comments of
`config/strategies/*.yaml`. Those values are produced by executing
`config_hash` and by replaying the captured postseason slates; nothing in
`data/` or `reports/` contains them, so without this artifact a reviewer has
no way to resolve them. (The four ENABLED+LIVE hashes are additionally
enforced by tests/test_live_config.py; fav_ml, dog_ml and pv_v2 are skipped
there — disabled, or an empty lineage that pools every hash — which is
exactly why they need a printed record.)

Two sections:

  1. Every strategy's current `config_hash`, its declared `hash_lineage`, and
     whether the hash is in it. The same data as `panthera-mvp hashes --json`.
  2. A read-only replay of the captured postseason slates (gameType F/D/L/W)
     through each enabled live engine, reporting picks, game-type passes and
     other passes. "Zero game-type passes" is the fix's observable claim.

Offline: reads data/games/games.csv and data/odds/lines.csv only, takes no
snapshot and spends no API credits. The replay fixes an empty Dossier and no
splits, so it measures WHAT THE GATE ADMITS, not what a live run would place
(a live run has the full season context and the captured splits).

Run from the repo root: .venv/bin/python scripts/proof_postseason_scope.py
(it imports panthera_mvp, so it needs the editable install)
Writes docs/proofs/postseason-scope.md and exits non-zero if the gate still
rejects a postseason game.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

from panthera_mvp import store
from panthera_mvp.clients.mlb import GameInfo
from panthera_mvp.config import load_strategy_configs
from panthera_mvp.hashes import _rows
from panthera_mvp.strategy.daytype import day_type
from panthera_mvp.strategy.dossier import Dossier
from panthera_mvp.strategy.movement import extract_game_prices, extract_totals_prices
from panthera_mvp.strategy.registry import StrategyContext, engines
from panthera_mvp.strategy.rules import Pass, Pick
from panthera_mvp.strategy.slots import assign_slots
from panthera_mvp.timeutil import parse_utc

POSTSEASON = ("F", "D", "L", "W")
OUT = Path("docs/proofs/postseason-scope.md")


def main() -> int:
    games, lines = store.load_games(), store.load_lines()
    if games.empty or lines.empty:
        print("no captured history; nothing to prove", file=sys.stderr)
        return 1
    lines = lines.dropna(subset=["game_pk"]).astype({"game_pk": int})
    post = games[games["game_type"].isin(POSTSEASON)]

    strategies = load_strategy_configs(known_engines=set(engines()))
    live = {
        sid: cfg
        for sid, cfg in sorted(strategies.items())
        if cfg["strategy"].get("enabled") and "live" in cfg["strategy"]["scope"]
    }

    out: list[str] = [
        "# Scope-fix proof: config hashes and postseason admission",
        "",
        "Generated by `python scripts/proof_postseason_scope.py` (offline; reads",
        "`data/games/games.csv` + `data/odds/lines.csv`, no network, no API credits).",
        "",
        "## 1. config_hash per strategy",
        "",
        "`config_hash` hashes the merged config minus `strategy`/`verdict`/`screen`/",
        "`meta` (`config.py` HASH_EXCLUDED_KEYS), so editing `hash_lineage` — which",
        "lives under `strategy` — cannot move the hash. An EMPTY lineage means \"pool",
        "every hash\" (`report.py`), never drift; a disabled strategy's drift is",
        "expected and inert.",
        "",
        "| strategy | config_hash | in lineage? | hash_lineage | enabled | scope |",
        "|---|---|---|---|---|---|",
    ]
    for r in _rows("mlb"):
        lineage = ", ".join(f"`{h}`" for h in r["hash_lineage"]) or "_(empty: pools all)_"
        out.append(
            f"| `{r['strategy_id']}` | `{r['config_hash']}` | "
            f"{'yes' if r['in_lineage'] else 'NO'} | {lineage} | "
            f"{'yes' if r['enabled'] else 'no'} | {'/'.join(r['scope'])} |"
        )

    by_type = ", ".join(
        f"{t}={int((post.game_type == t).sum())}"
        for t in POSTSEASON
        if (post.game_type == t).any()
    )
    out += [
        "",
        "## 2. Postseason admission",
        "",
        f"Captured postseason games: **{len(post)}** ({by_type}), "
        f"{post['game_date_et'].min()} to {post['game_date_et'].max()}.",
        "",
        "Each enabled live engine replayed over those slates. A **game-type pass**",
        "is the gate rejecting the game — the outage's signature. Any other pass is",
        "the strategy's own judgement. Picks and other-passes depend on an empty",
        "dossier and no splits, so treat them as what the gate ADMITS, not as what",
        "a live run would place.",
        "",
        "| strategy | picks | game-type passes | other passes |",
        "|---|---|---|---|",
    ]

    gate_rejections = 0
    for sid, scfg in live.items():
        engine = engines()[scfg["strategy"]["engine"]]
        picks = gated = other = 0
        for day in sorted(post["game_date_et"].unique()):
            day_games = post[post["game_date_et"] == day]
            lines_today = lines[lines["game_date_et"] == day]
            if lines_today.empty:
                continue
            events = (
                lines_today.drop_duplicates("game_pk")
                .set_index("game_pk")["odds_event_id"]
                .to_dict()
            )
            rows = list(day_games.itertuples(index=False))
            slot_map = assign_slots(
                [(int(r.game_pk), parse_utc(str(r.start_time_utc))) for r in rows],
                day_type(pd.Timestamp(day).date(), scfg),
                int(scfg.get("hybrid_boundary_hour_et", 18)),
            )
            for row in rows:
                game = GameInfo(
                    game_pk=int(row.game_pk),
                    game_date_et=str(row.game_date_et),
                    game_type=str(row.game_type),
                    status="Preview",
                    detailed_state="Scheduled",
                    start_utc=parse_utc(str(row.start_time_utc)),
                    doubleheader=str(row.doubleheader) if pd.notna(row.doubleheader) else "N",
                    game_number=int(row.game_number) if pd.notna(row.game_number) else 1,
                    home_team_id=int(row.home_team_id),
                    home_team=str(row.home_team),
                    away_team_id=int(row.away_team_id),
                    away_team=str(row.away_team),
                )
                event_id = events.get(game.game_pk)
                ctx = StrategyContext(
                    game=game,
                    odds_event_id=event_id,
                    prices=(
                        extract_game_prices(
                            lines_today, event_id, game.home_team, game.away_team
                        )
                        if event_id
                        else None
                    ),
                    totals=extract_totals_prices(lines_today, event_id) if event_id else None,
                    dossier=Dossier(),
                    splits=None,
                    slot_type=slot_map.get(game.game_pk),
                    cfg=scfg,
                )
                try:
                    outcome = engine(ctx)
                except Exception as exc:  # a bad captured price, not a gate result
                    other += 1
                    print(f"[{sid}] {game.game_pk} raised {type(exc).__name__}: {exc}",
                          file=sys.stderr)
                    continue
                if isinstance(outcome, Pick):
                    picks += 1
                elif isinstance(outcome, Pass) and outcome.reason.startswith(
                    "excluded_game_type"
                ):
                    gated += 1
                else:
                    other += 1
        gate_rejections += gated
        out.append(f"| `{sid}` | {picks} | {gated} | {other} |")

    out += [
        "",
        f"**Gate rejections across all live strategies: {gate_rejections}.** Before the",
        "fix every one of these games was rejected by the gate; `data/picks/passes.csv`",
        "holds 145 such passes from 2026-09-29 to 2026-10-14.",
        "",
        "Equivalence on the pre-fix domain (regular season) is proven separately and",
        "in CI by `tests/test_scope_fix_regression.py`.",
        "",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} (gate rejections: {gate_rejections})")
    return 1 if gate_rejections else 0


if __name__ == "__main__":
    raise SystemExit(main())
